"""Generate OpenSCAD source directly from the shared mesh representation."""

import json

from deck_builder.assembly import DeckAssembly, Role

COLORS: dict[Role, tuple[float, float, float]] = {
    "joist": (0.72, 0.53, 0.32),
    "rim": (0.72, 0.53, 0.32),
    "decking": (0.45, 0.26, 0.14),
    "support": (0.55, 0.55, 0.55),
    "border": (0.40, 0.22, 0.12),
    "stair_frame": (0.72, 0.53, 0.32),
    "stair_tread": (0.45, 0.26, 0.14),
}


def render_scad(assembly: DeckAssembly) -> str:
    """Serialize every part into an OpenSCAD solid.

    Args:
        assembly: Resolved parts with world-space geometry.

    Returns:
        OpenSCAD source in inches, ready to open in the OpenSCAD application.
    """
    lines = ["// Generated by deck-builder. Units: inches.", "union() {"]
    for part in assembly.parts:
        vertices = [[v.x, v.y, v.z] for v in part.geometry.vertices]
        # OpenSCAD expects clockwise faces when viewed from outside, unlike
        # the right-hand outward winding used by our internal meshes.
        faces = [list(reversed(face)) for face in part.geometry.faces]
        lines.extend(
            [
                f"  // {part.id}",
                f"  color({json.dumps(COLORS[part.role])})",
                f"    polyhedron(points={json.dumps(vertices)}, faces={json.dumps(faces)});",
            ]
        )
    return "\n".join([*lines, "}", ""])
